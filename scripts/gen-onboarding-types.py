#!/usr/bin/env python3
"""Generate the setup transport types from the authoritative JSON Schema."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = ROOT / "docs/contracts/schemas/onboarding.schema.json"
OUTPUT = ROOT / "ui/src/shared/generated/onboarding.ts"


def typename(node):
    if "$ref" in node:
        return node["$ref"].rsplit("/", 1)[1]
    if "const" in node:
        return json.dumps(node["const"])
    if "enum" in node:
        return " | ".join(json.dumps(v) for v in node["enum"])
    kind = node.get("type")
    if kind == "array":
        return f"({typename(node['items'])})[]"
    if kind in ("string", "boolean"):
        return kind
    if kind in ("integer", "number"):
        return "number"
    raise ValueError(f"Unsupported schema type: {node}")


def generate():
    schema = json.loads(SCHEMA.read_text())
    parts = ["// Generated by scripts/gen-onboarding-types.py from onboarding.schema.json. DO NOT EDIT.\n"]
    for name, definition in schema["$defs"].items():
        required = set(definition.get("required", []))
        parts.append(f"export interface {name} {{")
        for key, node in definition["properties"].items():
            optional = "" if key in required else "?"
            parts.append(f"  {key}{optional}: {typename(node)};")
        parts.append("}\n")
    return "\n".join(parts)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != output:
            raise SystemExit("onboarding.ts is stale; run python3 scripts/gen-onboarding-types.py")
        print("onboarding.ts matches the schema")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(output)
        print("Generated onboarding transport types")


if __name__ == "__main__":
    main()
